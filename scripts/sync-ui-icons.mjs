// Web/admin use the same reviewed Lucide geometry as the native app, without a new runtime dependency.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sources={
  exam:'clipboard-list', book:'book-open', results:'chart-pie', review:'repeat-2',
  chart:'chart-column', calculator:'calculator', calendar:'calendar-days',
  petition:'file-pen-line', report:'notebook-tabs', faq:'circle-question-mark',
  briefcase:'briefcase-business', catalogs:'shapes', topics:'network', examTypes:'tags', sources:'library-big',
  rules:'scale', target:'crosshair', cap:'graduation-cap',
  plus:'plus', arrow:'chevron-right', back:'chevron-left', arrowLeft:'arrow-left', arrowUp:'arrow-up', arrowDown:'arrow-down', jumpTop:'arrow-up-to-line',
  check:'check', completed:'circle-check', logout:'log-out', history:'rotate-ccw-clock',
  eye:'eye', eyeOff:'eye-off', flag:'flag', close:'x', shield:'shield-check',
  mail:'mail', lock:'lock-keyhole', external:'external-link',
  remove:'list-minus', trash:'trash', write:'square-pen', addExisting:'list-plus', attention:'triangle-alert', send:'send',
};
const pkg=JSON.parse(readFileSync(path.join(root,'node_modules/lucide-react-native/package.json'),'utf8'));
if(pkg.version!=='1.55.0')throw new Error('Lucide version changed; review icon geometry and licenses before syncing.');
const nodes={};
for(const [name,source] of Object.entries(sources)){
  const file=readFileSync(path.join(root,`node_modules/lucide-react-native/dist/esm/icons/${source}.mjs`),'utf8');
  const parsed=ts.createSourceFile(source+'.mjs',file,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
  let initializer;
  for(const statement of parsed.statements)if(ts.isVariableStatement(statement))for(const declaration of statement.declarationList.declarations)if(declaration.name.getText(parsed)==='__iconData')initializer=declaration.initializer;
  const literal=node=>{
    if(ts.isStringLiteral(node)||ts.isNumericLiteral(node))return ts.isNumericLiteral(node)?Number(node.text):node.text;
    if(ts.isArrayLiteralExpression(node))return node.elements.map(literal);
    if(ts.isObjectLiteralExpression(node))return Object.fromEntries(node.properties.map(property=>{
      if(!ts.isPropertyAssignment(property))throw new Error('Unsupported icon property; review source.');
      const key=ts.isIdentifier(property.name)||ts.isStringLiteral(property.name)?property.name.text:null;
      if(!key)throw new Error('Unsupported icon attribute; review source.');
      return [key,literal(property.initializer)];
    }));
    throw new Error('Expected static icon data; executable expressions are not supported.');
  };
  if(!initializer)throw new Error('Missing icon data: '+source);
  const data=literal(initializer);
  nodes[name]=data.node.map(([tag,{key,...attrs}])=>[tag,attrs]);
}
const featureNames=['exam','book','results','review','chart','calculator','calendar','petition','report','faq','briefcase','catalogs','topics','examTypes','sources'];
const output=`// Generated by scripts/sync-ui-icons.mjs from lucide-react-native ${pkg.version}.\n// ISC / MIT notices: ../LICENSE.icons. Review at 16–24 px after regenerating.\nexport type IconNode = readonly [tag: 'path' | 'rect' | 'circle' | 'line' | 'ellipse' | 'polyline' | 'polygon', attributes: Readonly<Record<string, string | number>>];\nexport const iconNodes = {\n${Object.entries(nodes).map(([name,data])=>`  ${name}: ${JSON.stringify(data)},`).join('\n')}\n} as const satisfies Record<string, readonly IconNode[]>;\nexport type IconName = keyof typeof iconNodes;\nexport const featureIconNames = ${JSON.stringify(featureNames)} as const satisfies readonly IconName[];\n`;
const outputs=[['packages/design-tokens/src/icons.ts',output],['packages/design-tokens/LICENSE.icons',readFileSync(path.join(root,'node_modules/lucide-react-native/LICENSE'),'utf8')]];
for(const [file,contents] of outputs){
  if(process.argv.includes('--check')){
    if(readFileSync(path.join(root,file),'utf8')!==contents)throw new Error('Stale icon file: '+file);
  }else writeFileSync(path.join(root,file),contents);
}
console.log(`${process.argv.includes('--check')?'Checked':'Synced'} ${Object.keys(nodes).length} icon definitions from Lucide ${pkg.version}.`);
