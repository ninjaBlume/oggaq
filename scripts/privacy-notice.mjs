// Append a new immutable notice version after legal:apply. Existing versions are never overwritten.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = resolve(root, 'config/privacy-notice.json');
const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : { current: '', notices: {} };
const version = process.argv.find(arg => arg.startsWith('--version='))?.split('=')[1] ?? manifest.current;
if (!/^\d{4}-\d{2}-\d{2}\.\d+$/.test(version)) throw new Error('Use --version=YYYY-MM-DD.N');
const file = `/legal/privacy-notices/${version}.html`;
const source = readFileSync(resolve(root, 'apps/web/public/legal/gizlilik.html'));
const hash = createHash('sha256').update(source).digest('hex');
const archivePath = resolve(root, `apps/web/public${file}`);
const previous = manifest.notices[version];
if (previous && (previous.sha256 !== hash || previous.file !== file)) throw new Error('This version already exists; use a NEW version for changed content.');
if (existsSync(archivePath) && !readFileSync(archivePath).equals(source)) throw new Error('An archived notice cannot be overwritten.');
const check = process.argv.includes('--check');
if (!check) {
  mkdirSync(dirname(archivePath), { recursive: true });
  if (!existsSync(archivePath)) writeFileSync(archivePath, source);
  manifest.current = version;
  manifest.notices[version] = { file, sha256: hash };
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}
if (manifest.current !== version || !previous && check) throw new Error('The current notice has not been archived.');
for (const notice of Object.values(manifest.notices)) {
  const actual = createHash('sha256').update(readFileSync(resolve(root, `apps/web/public${notice.file}`))).digest('hex');
  if (actual !== notice.sha256) throw new Error('An archived notice changed.');
}
const php = `<?php\n\n// Generated by scripts/privacy-notice.mjs; never edit archived version hashes.\nreturn [\n${Object.entries(manifest.notices).map(([v, n]) => `    '${v}' => '${n.sha256}',`).join('\n')}\n];\n`;
const phpPath = resolve(root, 'backend/config/privacy_notices.php');
if (check) {
  if (readFileSync(phpPath, 'utf8') !== php) throw new Error('Backend notice manifest is stale.');
} else writeFileSync(phpPath, php);
console.log(`Aydınlatma ${version}: arşiv ve SHA-256 doğrulandı.`);
