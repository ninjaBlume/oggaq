#!/usr/bin/env python3
"""Pin only the application's SMTP greeting; leave other senders unchanged."""

import argparse
import ipaddress
import os
from pathlib import Path
import re
import stat
import subprocess
import tempfile
import time

OLD_HELO = "${lookup dnsdb{>: defer_never,ptr=$sending_ip_address}{${listextract{1}{$value}}}{$primary_hostname}}"
TEMPLATE = Path("/etc/exim4/exim4.conf.template")
GENERATED = Path("/var/lib/exim4/config.autogenerated")


def validate_hostname(value):
    if len(value) > 253 or not re.fullmatch(r"[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?\.[a-z]{2,63}", value):
        raise ValueError("Geçersiz alan adı")
    if any(not label or len(label) > 63 or label.startswith("-") or label.endswith("-") for label in value.split(".")):
        raise ValueError("Geçersiz alan adı etiketi")


def expression(domain, hostname):
    validate_hostname(domain)
    validate_hostname(hostname)
    return "${if eq{${lc:${domain:$h_from:}}}{" + domain + "}{" + hostname + "}{" + OLD_HELO + "}}"


def patch_helo(source, domain, hostname):
    desired = expression(domain, hostname)
    sections = list(re.finditer(r"(?ms)^remote_smtp:\n(.*?)(?=^[A-Za-z_][A-Za-z_0-9]*:|\Z)", source))
    if len(sections) != 1:
        raise ValueError("Tek bir remote_smtp taşıyıcısı gerekli; değişiklik yapılmadı")
    section = sections[0]
    fields = list(re.finditer(r"(?m)^([ \t]+helo_data\s*=\s*)([^\n]+)$", section.group(1)))
    if len(fields) != 1:
        raise ValueError("Tek bir SMTP HELO satırı gerekli; değişiklik yapılmadı")
    field = fields[0]
    current = field.group(2)
    if current == desired:
        return source
    if current != OLD_HELO:
        raise ValueError("SMTP HELO özel/değişmiş; elle inceleme gerekli")
    begin = section.start(1) + field.start(2)
    end = section.start(1) + field.end(2)
    return source[:begin] + desired + source[end:]


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def check_public_dns(hostname, address):
    ipaddress.IPv4Address(address)
    # The host's resolver can synthesize an old /etc/hosts PTR; use public DNS.
    forward = run("dig", "@1.1.1.1", "+time=5", "+tries=1", "+short", "A", hostname).splitlines()
    reverse = run("dig", "@1.1.1.1", "+time=5", "+tries=1", "+short", "-x", address).splitlines()
    if address not in forward or hostname + "." not in reverse:
        raise ValueError("Genel DNS ileri/ters eşleşmesi doğrulanmadı; değişiklik yapılmadı")


def stage(source, parent, metadata=None):
    fd, name = tempfile.mkstemp(prefix=".oggsor-helo-", dir=parent)
    path = Path(name)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(source)
            stream.flush()
            os.fsync(stream.fileno())
        if metadata is not None:
            os.chown(path, metadata.st_uid, metadata.st_gid)
            path.chmod(stat.S_IMODE(metadata.st_mode))
        return path
    except BaseException:
        path.unlink(missing_ok=True)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--domain", required=True)
    parser.add_argument("--hostname", required=True)
    parser.add_argument("--public-ip", required=True)
    parser.add_argument("--apply", action="store_true", help="Root ile doğrulanmış değişikliği uygular")
    args = parser.parse_args()
    validate_hostname(args.domain)
    validate_hostname(args.hostname)
    check_public_dns(args.hostname, args.public_ip)
    if args.apply and os.geteuid() != 0:
        raise RuntimeError("Uygulama root gerektirir; sudo ile çalıştırın")
    target = TEMPLATE if args.apply else GENERATED
    if target.is_symlink():
        raise RuntimeError("Symlink yapılandırması elle incelenmeli")
    source = target.read_text()
    candidate = patch_helo(source, args.domain, args.hostname)
    # Validate the complete candidate with the installed host Exim, never a mock config.
    metadata = target.stat() if args.apply else None
    staged = stage(candidate, str(target.parent) if args.apply else None, metadata)
    try:
        run("/usr/sbin/exim4", "-C", str(staged), "-bV")
        if not args.apply:
            print("Ön kontrol geçti: genel DNS ve aday Exim yapılandırması geçerli; hiçbir dosya değiştirilmedi.")
            return
        if source == candidate:
            print("İstenen uygulama SMTP kimliği zaten etkin; değişiklik yok.")
            return
        # Protected, local backup; neither private config nor unrelated domains leave this host.
        backup = target.with_name(target.name + ".oggsor-helo-" + str(time.time_ns()) + ".bak")
        with open(backup, "x", opener=lambda path, flags: os.open(path, flags, 0o600)) as stream:
            stream.write(source)
        if target.read_text() != source:
            raise RuntimeError("Yapılandırma ön kontrol sırasında değişti; uygulama iptal edildi")
        os.replace(staged, target)
        try:
            run("systemctl", "reload", "exim4")
            run("/usr/sbin/exim4", "-bV")
            run("systemctl", "is-active", "--quiet", "exim4")
            generated = GENERATED.read_text()
            if patch_helo(generated, args.domain, args.hostname) != generated or expression(args.domain, args.hostname) not in generated:
                raise RuntimeError("Üretilen yapılandırma yeni HELO değerini taşımıyor")
        except BaseException:
            rollback = stage(source, str(target.parent), metadata)
            os.replace(rollback, target)
            run("systemctl", "reload", "exim4")
            raise RuntimeError("Son kontrol başarısız; önceki şablon geri yüklendi") from None
        print("Uygulama SMTP kimliği güncellendi; diğer gönderenler eski davranışı koruyor. Yedek: " + str(backup))
    finally:
        staged.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
