import { colorRoles, darkPalette, lightPalette, shape } from './index.ts';
import type { Palette } from './index.ts';

const name = (role: string) => `--c-${role.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}`;
const declarations = (palette: Palette, indent: string) => colorRoles.map((role) => `${indent}${name(role)}: ${palette[role]};`).join('\n');

export function cssTokens() {
  return `/* Generated by packages/design-tokens/scripts/generate-css.ts from src/index.ts. Do not edit by hand. */
:root {
  color-scheme: light;
${declarations(lightPalette, '  ')}
  --radius-s: ${shape.small}px;
  --radius-m: ${shape.medium}px;
  --radius-l: ${shape.large}px;
  --radius-xl: ${shape.extraLarge}px;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${declarations(darkPalette, '    ')}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${declarations(darkPalette, '  ')}
}
`;
}
